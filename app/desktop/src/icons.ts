export type IconName = keyof typeof BODIES & string;

/** Build an inline SVG string for the given icon. */
export function icon(name: string, extraClass = ""): string {
  const body = BODIES[name];
  if (!body) return "";
  const cls = `lucide lucide-${name}${extraClass ? " " + extraClass : ""}`;
  return (
    `<svg class="${cls}" xmlns="http://www.w3.org/2000/svg" width="24" ` +
    `height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true">${body}</svg>`
  );
}

/** Replace any element with a `data-icon="name"` attribute with its SVG. */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    const name = el.dataset.icon;
    if (name && !el.dataset.iconDone) {
      el.innerHTML = icon(name);
      el.dataset.iconDone = "1";
    }
  });
}
