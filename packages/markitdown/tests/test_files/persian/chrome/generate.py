"""Optional fixture authoring tool for the Chromium-produced Persian PDF.

Prints cases.html with headless Chrome/Chromium and derives the logical ground
truth from the authored HTML itself, never from extraction results. Tests never
run this; chrome_cases.pdf is a committed artifact (Skia embeds a creation
date, so regenerated bytes differ even when the content is identical).

    CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" \\
        python generate.py
"""

import hashlib
import json
import os
import re
import subprocess
from html.parser import HTMLParser
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent


class Truth(HTMLParser):
    """Collect per-section text blocks and table matrices in logical order."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.cases = {}
        self.section = self.text = self.row = self.rows = None
        self.item = 0

    def handle_starttag(self, tag, attrs):
        if tag == "section":
            self.section = dict(attrs)["id"]
            self.cases[self.section] = {"blocks": []}
        elif tag in ("p", "h1", "h2", "li", "td", "th"):
            self.text = []
        elif tag == "ol":
            self.item = 0
        elif tag == "table":
            self.rows = []
        elif tag == "tr":
            self.row = []

    def handle_data(self, data):
        if self.text is not None:
            self.text.append(data)

    def handle_endtag(self, tag):
        if tag in ("p", "h1", "h2", "li", "td", "th"):
            text = re.sub(r"\s+", " ", "".join(self.text)).strip()
            self.text = None
            if tag in ("td", "th"):
                self.row.append(text)
            else:
                if tag == "li":
                    self.item += 1
                    text = f"{self.item}. {text}"
                self.cases[self.section]["blocks"].append(text)
        elif tag == "tr":
            self.rows.append(self.row)
        elif tag == "table":
            self.cases[self.section] = {"table": self.rows}


def main():
    chrome = os.environ.get("CHROME") or "google-chrome"
    pdf = HERE / "chrome_cases.pdf"
    subprocess.run(
        [
            chrome,
            "--headless=new",
            "--disable-gpu",
            "--no-pdf-header-footer",
            "--allow-file-access-from-files",
            f"--print-to-pdf={pdf}",
            (HERE / "cases.html").as_uri(),
        ],
        check=True,
    )
    parser = Truth()
    parser.feed((HERE / "cases.html").read_text(encoding="utf-8"))
    (HERE / "expected.json").write_text(
        json.dumps(parser.cases, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    sums = json.loads((ROOT / "sha256.json").read_text(encoding="utf-8"))
    for path in (pdf, HERE / "cases.html", HERE / "expected.json"):
        sums[str(path.relative_to(ROOT))] = hashlib.sha256(
            path.read_bytes()
        ).hexdigest()
    (ROOT / "sha256.json").write_text(
        json.dumps(sums, indent=2) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
