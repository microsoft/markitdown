"""
Reproducer for microsoft/markitdown issue #1845:
Academic PDF conversion outputs non-standard Markdown with broken formatting.

Root cause: pdfminer.six extracts text in PDF storage order, not visual reading
order. Two-column journal layouts get interleaved mid-sentence between columns,
and table cells come out scrambled.
"""

