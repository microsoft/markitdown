def create_two_column_pdf(path):
    c = canvas.Canvas(path, pagesize=letter)
    width, height = letter

    # Title
    c.setFont("Helvetica-Bold", 14)
    c.drawCentredString(width / 2, height - 0.75 * inch,
        "Iron-Cycling CW-MFC Enhanced Removal of Sartans")
    c.setFont("Helvetica", 10)
    c.drawCentredString(width / 2, height - 1.05 * inch,
        "Zhang et al. | Environmental Science & Technology | 2026")

    # Divider line
    c.setStrokeColor(colors.black)
    c.line(inch, height - 1.2 * inch, width - inch, height - 1.2 * inch)

    # Column layout
    col_width = (width - 2.5 * inch) / 2
    left_x = inch
    right_x = inch + col_width + 0.5 * inch
    top_y = height - 1.5 * inch
    line_height = 13

    def draw_column(x, lines, start_y):
        c.setFont("Helvetica", 9)
        y = start_y
        for line in lines:
            if line and line[0].isdigit() and "." in line[:3]:
                c.setFont("Helvetica-Bold", 9)
                c.drawString(x, y, line)
                c.setFont("Helvetica", 9)
            elif line in ("Abstract",):
                c.setFont("Helvetica-Bold", 9)
                c.drawString(x, y, line)
                c.setFont("Helvetica", 9)
            else:
                # Wrap text within column width
                words = line.split()
                current = ""
                for word in words:
                    test = (current + " " + word).strip()
                    if c.stringWidth(test, "Helvetica", 9) < col_width - 10:
                        current = test
                    else:
                        c.drawString(x, y, current)
                        y -= line_height
                        current = word
                if current:
                    c.drawString(x, y, current)
            y -= line_height
        return y

    draw_column(left_x, LEFT_COL_TEXT, top_y)
    draw_column(right_x, RIGHT_COL_TEXT, top_y)

    # Column separator
    mid_x = inch + col_width + 0.25 * inch
    c.setDash(3, 3)
    c.line(mid_x, height - 1.25 * inch, mid_x, 1.5 * inch)

    c.save()
    print(f"Created: {path}")


def run_markitdown(path):
    md = MarkItDown()
    result = md.convert(path)
    return result.text_content


def main():
    print("=== Reproducer for issue #1845 ===\n")

    create_two_column_pdf(PDF_PATH)

    print("Running markitdown on two-column academic PDF...\n")
    output = run_markitdown(PDF_PATH)

    print("--- markitdown output ---")
    print(output)
    print("--- end of output ---\n")

    # Diagnose the interleaving problem
    lines = [l for l in output.splitlines() if l.strip()]
    left_markers = ["Abstract", "Introduction", "Materials", "Methods"]
    right_markers = ["Results", "Discussion", "Conclusion"]

    print("=== Issue diagnosis ===")
    print("Expected: left column content followed by right column content.")
    print("Actual order of section headers found:\n")
    for i, line in enumerate(lines):
        for m in left_markers + right_markers:
            if m in line:
                side = "LEFT col" if m in left_markers else "RIGHT col"
                print(f"  line {i:3d}: [{side}] {line.strip()}")

    print("\nIf LEFT and RIGHT column sections interleave, the bug is reproduced.")


if __name__ == "__main__":
    main()
